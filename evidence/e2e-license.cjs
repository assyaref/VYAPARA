// Full licensing E2E: start sync server with licensing → generate serial → activate in desktop app → setup admin
const { _electron: electron } = require('playwright');
const { spawn } = require('node:child_process');
const path = require('path');
const os = require('os');
const fs = require('fs');
const crypto = require('node:crypto');
const root = process.cwd();
const results = [];
const check = (name, ok) => { results.push({ name, ok }); console.log(`${ok ? 'PASS' : 'FAIL'} | ${name}`); };

const SYNC_PORT = 8991;
const ENROLLMENT = 'e2e-licensing-' + crypto.randomBytes(4).toString('hex');
const ADMIN_TOKEN = 'lic-e2e-admin-' + crypto.randomBytes(8).toString('hex');
const DB = path.join(os.tmpdir(), `vyapara-lic-e2e-${Date.now()}.db`);

function waitForServer(url, tries = 50) {
  return new Promise((resolve, reject) => {
    let n = 0;
    const tick = async () => {
      try {
        const res = await fetch(url, { method: 'GET' });
        if (res.ok) return resolve();
      } catch {}
      if (++n >= tries) return reject(new Error('server did not start'));
      setTimeout(tick, 200);
    };
    tick();
  });
}

(async () => {
  // 1. start sync server with licensing migration
  const server = spawn(process.execPath, [path.join(root, 'apps/sync-server/dist/server.mjs')], {
    env: { ...process.env, SYNC_DB_PATH: DB, SYNC_ENROLLMENT_SECRET: ENROLLMENT, SYNC_ADMIN_TOKEN: ADMIN_TOKEN, PORT: String(SYNC_PORT), HOST: '127.0.0.1' },
    stdio: 'pipe',
  });
  server.stdout?.on('data', (d) => process.env.DEBUG && console.log('[sync]', String(d).trim()));
  server.stderr?.on('data', (d) => console.error('[sync-err]', String(d).trim()));

  let licenseKey = null;
  try {
    await waitForServer(`http://127.0.0.1:${SYNC_PORT}/v1/sync/health`);
    console.log('[e2e-lic] sync server up');

    // 2. generate license via admin API
    const genRes = await fetch(`http://127.0.0.1:${SYNC_PORT}/admin/licenses`, {
      method: 'POST',
      headers: { authorization: `Bearer ${ADMIN_TOKEN}`, 'content-type': 'application/json' },
      body: JSON.stringify({ organizationName: 'Toko Uji Lisensi', maxActivations: 1 }),
    });
    const genBody = await genRes.json();
    if (!genBody?.ok || !genBody.data?.key) throw new Error('license generate failed: ' + JSON.stringify(genBody));
    licenseKey = genBody.data.key;
    console.log('[e2e-lic] license generated');

  } catch (e) {
    console.error('FATAL:', e);
    server.kill();
    process.exit(1);
  }

  check('License generated by admin API', typeof licenseKey === 'string' && licenseKey.startsWith('VYPR-'));

  // 3. launch desktop with fresh profile
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'vyapara-e2e-lic-'));
  const app = await electron.launch({
    executablePath: path.join(root, 'node_modules', 'electron', 'dist', 'electron.exe'),
    args: ['--no-sandbox', `--user-data-dir=${profile}`, path.join(root, 'apps', 'desktop', 'out', 'main', 'main.js')],
    env: { ...process.env, NODE_ENV: 'production', VYAPARA_FORCE_LICENSE: '1' },
    timeout: 45000,
  });
  const page = await app.firstWindow({ timeout: 45000 });
  page.on('pageerror', (e) => console.log('[pageerror]', e.message));
  const bodyText = () => page.evaluate(() => document.body.innerText || '');

  await page.waitForTimeout(2500);
  let txt = await bodyText();
  check('License activation screen shown (no setup yet)', /Aktivasi Lisensi|berlisensi/i.test(txt) && !/Siapkan Administrator/i.test(txt));

  // 4. fill activation form
  await page.fill('#license-server', `http://127.0.0.1:${SYNC_PORT}`);
  await page.fill('#license-serial', licenseKey);
  await page.fill('#license-org', 'Toko Uji Lisensi');
  await page.locator('button:has-text("Aktivasi Sekarang")').click();
  await page.waitForTimeout(2500);
  txt = await bodyText();
  check('Activation succeeded → setup screen reached', /Siapkan Administrator/i.test(txt));

  // 5. verify license persisted in DB settings
  const lic = await page.evaluate(async () => {
    const res = await window.vyapara.getLicenseStatus();
    return res?.ok ? res.data : null;
  });
  check('License stored locally', lic?.state === 'licensed');

  // 6. complete admin setup to prove full app boots after activation
  await page.fill('#name', 'Lic Admin');
  await page.fill('#email', 'lic@e2e.test');
  await page.fill('#password', 'rahasia123456');
  await page.fill('#confirm', 'rahasia123456');
  await page.click('button[type="submit"]');
  await page.waitForFunction(() => /omzet hari ini/i.test(document.body.innerText || ''), undefined, { timeout: 15000 });
  check('Admin setup completes after activation', true);

  await app.close();
  server.kill();
  fs.rmSync(profile, { recursive: true, force: true });
  fs.rmSync(DB, { force: true });
  const pass = results.filter((r) => r.ok).length;
  console.log(`SUMMARY ${pass} PASS / ${results.length - pass} FAIL (${results.length} checks)`);
  process.exit(pass === results.length ? 0 : 1);
})().catch((e) => { console.error('E2E-LIC ERROR:', e); process.exit(1); });
